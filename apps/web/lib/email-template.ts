interface FacturaEmailData {
  numero: string
  emisorReceptor: string
  baseImponible: number
  iva: number
  total: number
}

interface PerfilEmailData {
  logoBase64?: string | null
  notasPie?: string | null
  nombre?: string | null
}

function formatEuro(cents: number): string {
  return new Intl.NumberFormat('es-ES', { style: 'currency', currency: 'EUR' }).format(cents / 100)
}

export function generarEmailFactura(
  factura: FacturaEmailData,
  perfil: PerfilEmailData,
  idioma: string = 'es'
): string {
  const logo = perfil.logoBase64 || ''
  const color = '#eab308'
  const esEN = idioma === 'en'

  return `
    <!DOCTYPE html>
    <html>
    <head><meta charset="utf-8"></head>
    <body style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto;">
      <div style="background: ${color}; padding: 20px; text-align: center;">
        ${logo ? `<img src="${logo}" style="max-height: 60px;" />` : '<h1 style="color: #000;">MantiGestor</h1>'}
      </div>
      <div style="padding: 20px;">
        <h2>${esEN ? 'Invoice' : 'Factura'} ${factura.numero}</h2>
        <p>${esEN ? 'Dear' : 'Estimado/a'} ${factura.emisorReceptor},</p>
        <p>${esEN ? 'Please find attached invoice' : 'Adjuntamos la factura'} ${factura.numero} ${esEN ? 'for' : 'por'} ${formatEuro(factura.total)}.</p>
        <table style="width: 100%; border-collapse: collapse; margin: 20px 0;">
          <tr><td style="padding: 8px; border-bottom: 1px solid #eee;"><strong>${esEN ? 'Amount' : 'Importe'}</strong></td><td style="padding: 8px; border-bottom: 1px solid #eee;">${formatEuro(factura.baseImponible)}</td></tr>
          <tr><td style="padding: 8px; border-bottom: 1px solid #eee;"><strong>IVA</strong></td><td style="padding: 8px; border-bottom: 1px solid #eee;">${formatEuro(factura.iva)}</td></tr>
          <tr><td style="padding: 8px; border-bottom: 1px solid #eee;"><strong>${esEN ? 'Total' : 'Total'}</strong></td><td style="padding: 8px; border-bottom: 1px solid #eee;"><strong>${formatEuro(factura.total)}</strong></td></tr>
        </table>
        ${perfil.notasPie ? `<p style="color: #666; font-size: 12px;">${perfil.notasPie}</p>` : ''}
      </div>
      <div style="padding: 12px 20px; text-align: center; color: #999; font-size: 11px;">
        ${esEN ? 'Generated by MantiGestor' : 'Generado por MantiGestor'}
      </div>
    </body>
    </html>
  `
}
